/*
 * v15: the cache used to key on videoId alone, so a translation produced for an
 * earlier analysis of the same video was silently paired with a newer, longer
 * one — the tail then rendered in the source language with no indication.
 * Fingerprints tie an entry to the exact analysis it was produced from.
 */
function overviewFingerprint(analysis) {
  const chapters = Array.isArray(analysis?.chapters) ? analysis.chapters : [];
  const quotes = Array.isArray(analysis?.keyQuotes) ? analysis.keyQuotes : [];
  const first = chapters.length ? chapters[0]?.timestampSeconds ?? -1 : -1;
  const last = chapters.length
    ? chapters[chapters.length - 1]?.timestampSeconds ?? -1
    : -1;
  const titles = chapters
    .map((ch) => String(ch.title || ""))
    .join("|")
    .slice(0, 400);
  return `${chapters.length}|${quotes.length}|${first}|${last}|${titles}`;
}

function getCachedOverviewTranslation(videoId, analysis) {
  const entry = overviewTranslationCache.get(videoId);
  if (!entry || typeof entry !== "object") return null;
  if (!entry.fingerprint || entry.fingerprint !== overviewFingerprint(analysis)) {
    return null;
  }
  return entry;
}

