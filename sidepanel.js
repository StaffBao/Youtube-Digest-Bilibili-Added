/*
 * Maps a subtitle-track language code to the English language name the Overview
 * prompt expects. Chinese variants are normalized explicitly (the rest of the
 * code compares against "Simplified Chinese"); everything else goes through
 * Intl.DisplayNames so Korean/Japanese/German/Spanish/... all resolve properly.
 */
function languageCodeToName(code) {
  const c = String(code || "").trim().toLowerCase();
  if (!c) return null;
  if (c === "ai-zh" || c === "zh" || c === "zh-cn" || c === "zh-hans" || c === "zh-hans-cn") {
    return "Simplified Chinese";
  }
  if (c === "zh-hant" || c === "zh-tw" || c === "zh-hk") return "Traditional Chinese";
  try {
    const name = new Intl.DisplayNames(["en"], { type: "language" }).of(c);
    if (name && name !== c && name !== "Unknown") return name;
  } catch (_e) {
    // Fall through to script detection below.
  }
  return null;
}

/*
 * Script-based fallback for when there is no subtitle-track language code
 * (e.g. pure ASR). Hangul -> Korean, kana -> Japanese, CJK -> Chinese, else English.
 */
function detectTextLanguageName(text) {
  const sample = String(text || "").slice(0, 5000);
  const cjk = (sample.match(/[一-鿿]/g) || []).length;
  const kana = (sample.match(/[぀-ヿ]/g) || []).length;
  const hangul = (sample.match(/[가-힯]/g) || []).length;
  const latin = (sample.match(/[a-zA-Z]/g) || []).length;
  const total = cjk + kana + hangul + latin;
  if (!total) return "English";
  if (hangul >= total * 0.3) return "Korean";
  if (kana >= total * 0.15) return "Japanese";
  if (cjk >= latin && cjk > 0) return "Simplified Chinese";
  return "English";
}

