function isSupportedVideoUrl(url) {
  const value = String(url || "");
  if (value.startsWith("https://www.youtube.com")) return true;
  if (
    bilibiliEnabled &&
    value.startsWith("https://www.bilibili.com/video/")
  ) {
    return true;
  }
  return false;
}

function platformForUrl(url) {
  return String(url || "").includes("bilibili.com") ? "bilibili" : "youtube";
}

async function checkCurrentTab() {
  try {
    // Tab URL patterns reflect whether Bilibili mode is enabled.
    const supportedUrlPatterns = bilibiliEnabled
      ? ["https://www.youtube.com/watch*", "https://www.bilibili.com/video/*"]
      : ["https://www.youtube.com/watch*"];

    // Try multiple strategies to find a supported video tab
    let tab = null;

    // Strategy 1: Active tab in last focused window
    let tabs = await chrome.tabs.query({
      active: true,
      lastFocusedWindow: true,
    });
    if (tabs[0] && isSupportedVideoUrl(tabs[0].url)) {
      tab = tabs[0];
    }

    // Strategy 2: Any active supported video tab
    if (!tab) {
      tabs = await chrome.tabs.query({
        url: supportedUrlPatterns,
        active: true,
      });
      if (tabs[0]) tab = tabs[0];
    }

    // Strategy 3: Any supported video tab (last resort)
    if (!tab) {
      tabs = await chrome.tabs.query({
        url: supportedUrlPatterns,
      });
      if (tabs[0]) tab = tabs[0];
    }

    debugLog("[Youtube Bilibili Digest Panel] Found tab:", tab?.id, tab?.url);

    if (!tab?.url) {
      showState("welcome");
      return;
    }

    // Store the tab ID for reliable messaging later
    youtubeTabId = tab.id;

    const videoId = extractVideoId(tab.url);

    if (videoId) {
      currentVideoUrl = tab.url;
      currentPlatform = platformForUrl(tab.url);

      try {
        // Route through background script for reliable message passing
        const result = await chrome.runtime.sendMessage({
          action: "relayToContent",
          payload: { action: "getVideoInfo" },
        });
        debugLog("[Youtube Bilibili Digest Panel] getVideoInfo result:", result);
        if (result.success && result.response) {
          currentVideoTitle = result.response.title || "";
          currentChannelName = result.response.channelName || "";
          currentVideoDescription = result.response.description || "";
          currentVideoDuration = result.response.duration || 0;
        }
      } catch (e) {
        console.error("[Youtube Bilibili Digest Panel] getVideoInfo error:", e);
        currentVideoTitle = "";
        currentChannelName = "";
        currentVideoDescription = "";
        currentVideoDuration = 0;
      }

      startDigest(videoId, tab.url);
    } else {
      showState("welcome");
    }
  } catch (error) {
    console.error("Tab check error:", error);
    showState("welcome");
  }
}

function extractVideoId(url) {
  try {
    const urlObj = new URL(url);

    if (urlObj.hostname.includes("bilibili.com")) {
      const match = urlObj.pathname.match(/\/video\/(BV[0-9A-Za-z]{10})/);
      return match ? match[1] : null;
    }

    if (
      urlObj.hostname.includes("youtube.com") &&
      urlObj.searchParams.has("v")
    ) {
      return urlObj.searchParams.get("v");
    }

    if (urlObj.hostname === "youtu.be") {
      return urlObj.pathname.slice(1);
    }

    if (urlObj.pathname.startsWith("/embed/")) {
      return urlObj.pathname.split("/")[2];
    }

    return null;
  } catch {
    return null;
  }
}

