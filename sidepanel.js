async function handleOverviewModeChange(mode) {
  if (!["original", "zh", "bilingual"].includes(mode)) return;
  if (mode === currentOverviewMode) return;

  currentOverviewMode = mode;
  overviewTranslationGeneration += 1;
  setOverviewModeButtons(mode);

  if (mode === "original") {
    renderAnalysisWithMode();
    return;
  }

  /* A Chinese-language analysis IS the Chinese view: translating it would be
     Chinese-into-Chinese. Render verbatim and spend nothing. */
  if (mode === "zh" && analysisIsAllChinese(currentAnalysis)) {
    renderAnalysisWithMode();
    return;
  }

  // If we already have a cached translation for this video, render immediately
  if (overviewTranslationCache.has(currentVideoId)) {
    renderAnalysisWithMode();
    return;
  }

  // Otherwise, trigger translation
  await translateOverview();
}

async function translateOverview() {
  if (!currentAnalysis) return;
  if (currentOverviewMode === "original") return;
  if (currentOverviewMode === "zh" && analysisIsAllChinese(currentAnalysis)) {
    return;
  }

  const generation = overviewTranslationGeneration;
  const videoId = currentVideoId;
  setOverviewTranslatingSpinner(true);

  try {
    const result = await sendTranslationMessage({
      action: "translateOverview",
      analysis: {
        chapters: (currentAnalysis.chapters || []).map((ch) => ({
          title: ch.title,
          summary: ch.summary || "",
        })),
        keyQuotes: (currentAnalysis.keyQuotes || []).map((q) => ({
          quote: q.quote,
        })),
      },
      videoTitle: currentVideoTitle,
    });

    if (generation !== overviewTranslationGeneration || videoId !== currentVideoId) return;

    if (result?.success && result.translatedAnalysis) {
      overviewTranslationCache.set(videoId, {
        fingerprint: overviewFingerprint(currentAnalysis),
        translatedAnalysis: result.translatedAnalysis,
        missing: result.missing || { chapters: [], keyQuotes: [] },
      });
      renderAnalysisWithMode();
    } else {
      console.error("[Youtube Bilibili Digest] Overview translation failed:", result?.error);
      // Fallback to original
      renderAnalysisWithMode();
    }
  } catch (error) {
    if (generation !== overviewTranslationGeneration) return;
    console.error("[Youtube Bilibili Digest] Overview translation error:", error);
    renderAnalysisWithMode();
  } finally {
    if (generation === overviewTranslationGeneration) {
      setOverviewTranslatingSpinner(false);
    }
  }
}

