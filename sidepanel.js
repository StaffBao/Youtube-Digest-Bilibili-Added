/*
 * v17: an overview may mix languages chapter by chapter (a video can switch
 * spoken language mid-way), so "is this analysis Chinese?" is answered from the
 * chapters themselves. CJK-vs-Latin script detection is reliable per chapter;
 * only Latin-vs-Latin (German vs English) is not, and nothing keys off that.
 */
function isChineseText(text) {
  return detectTextLanguageName(text) === "Simplified Chinese";
}

function chapterIsChinese(chapter) {
  return isChineseText(`${chapter?.title || ""} ${chapter?.summary || ""}`);
}

function analysisIsAllChinese(analysis) {
  const chapters = Array.isArray(analysis?.chapters) ? analysis.chapters : [];
  return chapters.length > 0 && chapters.every(chapterIsChinese);
}

/*
 * Script-level audit of per-chapter language compliance. CJK-vs-Latin is
 * detectable client-side; Latin-vs-Latin is not. A mismatch only warns — there
 * is no regenerate entry anymore, so this console line is the diagnostic.
 */
function auditOverviewChapterLanguages(analysis, timestampedText) {
  const chapters = Array.isArray(analysis?.chapters) ? analysis.chapters : [];
  const lines = String(timestampedText || "")
    .split("\n")
    .map((line) => {
      const m = line.match(/^\[(\d+):(\d{2})\]\s*(.*)$/);
      return m ? { seconds: Number(m[1]) * 60 + Number(m[2]), text: m[3] } : null;
    })
    .filter(Boolean);
  if (!chapters.length || !lines.length) return;
  const mismatches = [];
  chapters.forEach((chapter, i) => {
    const start = Number(chapter.timestampSeconds) || 0;
    const end =
      i + 1 < chapters.length
        ? Number(chapters[i + 1].timestampSeconds) || Infinity
        : Infinity;
    const spoken = lines
      .filter((l) => l.seconds >= start && l.seconds < end)
      .map((l) => l.text)
      .join(" ");
    if (spoken.trim() && isChineseText(spoken) !== chapterIsChinese(chapter)) {
      mismatches.push({ index: i, timestamp: chapter.timestamp });
    }
  });
  if (mismatches.length) {
    // console.log, not warn: keep this out of chrome://extensions' Errors page.
    // It is a diagnostic for model disobedience, not a user-facing failure.
    console.log(
      "[Youtube Bilibili Digest Panel] Overview chapters not in the spoken language of their range:",
      mismatches.map((m) => `#${m.index}@${m.timestamp}`).join(", "),
    );
  }
}

/*
 * Builds an authoritative spoken-language timeline from the transcript so the
 * analysis model does not have to guess per-chapter language itself (it gets
 * this wrong in a Chinese-dominated context). CJK vs Latin is detectable
 * client-side via script counting; Latin-vs-Latin (German vs English) is not,
 * so those segments are labelled 非中文 for the model to read from the lines.
 * Short runs are absorbed into the previous run to swallow single-name /
 * loanword lines that would otherwise split the timeline into noise.
 */
function buildTranscriptLanguageTimeline(timestampedText) {
  const MIN_RUN_SECONDS = 15;
  const lines = String(timestampedText || "")
    .split("\n")
    .map((line) => {
      const m = line.match(/^\[(\d+):(\d{2})\]\s*(.*)$/);
      return m ? { seconds: Number(m[1]) * 60 + Number(m[2]), text: m[3] } : null;
    })
    .filter((entry) => entry && entry.text.trim());
  if (!lines.length) return "";
  const clock = (sec) =>
    `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, "0")}`;
  const runs = [];
  lines.forEach((line) => {
    const bucket = isChineseText(line.text) ? "中文" : "非中文";
    const last = runs[runs.length - 1];
    if (last && last.bucket === bucket) last.end = line.seconds;
    else runs.push({ bucket, start: line.seconds, end: line.seconds });
  });
  const merged = [];
  runs.forEach((run) => {
    const last = merged[merged.length - 1];
    if (
      last &&
      (run.bucket === last.bucket || run.end - run.start < MIN_RUN_SECONDS)
    ) {
      last.end = run.end;
    } else {
      merged.push({ ...run });
    }
  });
  const lastRun = merged[merged.length - 1];
  return merged
    .map((run) =>
      run === lastRun
        ? `[${clock(run.start)}–end] ${run.bucket}`
        : `[${clock(run.start)}–${clock(run.end)}] ${run.bucket}`,
    )
    .join("\n");
}

