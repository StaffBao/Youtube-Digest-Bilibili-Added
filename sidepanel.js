// ============================================================
// v10 — AI SUBTITLE PUNCTUATION RESTORATION (R2)
// ============================================================
//
// Bilibili `ai-zh` (and YouTube ASR Chinese) tracks often arrive as unbroken
// character runs. groupTranscriptEntries relies on punctuation to find sentence
// boundaries, so those runs collapse into 320-char "walls". Tier-0 below is a
// free, insert-only local heuristic applied at render time; Tier-1 is the
// one-click LLM restoration (handlePunctuateTranscript) cached per segment.

// Namespace is prefixed with `${videoId}:` so saveToCache's existing prefix
// filter persists it for free — no cache-schema change required.
/*
 * `ns` separates transcripts of different origin for the SAME video: segment ids
 * are `segment-<index>-<startMs>` with no origin component, so an adopted
 * original and the platform track it displaced both produce `segment-0-0`. The
 * default "semantic" scope keeps every pre-v15 cache entry valid.
 */
function punctCacheKey(segment, ns) {
  const scope = ns && ns !== "held" ? ns : "semantic";
  return `${currentVideoId}:punct:${scope}:${segment.id}`;
}

// True when the transcript is a CJK run that is essentially missing
// punctuation. Platform-agnostic: YouTube ASR Chinese benefits too.
function needsPunctuationFix(text) {
  /*
   * Judges the text passed in, defaulting to the held transcript. The zh mode can
   * render a different track from the one currentTranscriptText describes, and
   * heuristicPunctuate inserts full-width marks that must never reach a Latin or
   * Kana run.
   */
  const judged = String(
    text === undefined ? currentTranscriptText || "" : text || "",
  );
  const key = `${currentVideoId}|${currentTranscriptLanguage}|${judged.length}|${judged.slice(0, 64)}`;
  if (punctFixMemo.key === key) return punctFixMemo.value;

  const value = textNeedsPunctuationFix(judged);
  punctFixMemo = { key, value };
  return value;
}

// v11 (W8): the character scan behind needsPunctuationFix, lifted into a pure
// function so the Docs timestamp channel can ask the SAME question about an
// arbitrary text (a fetched source track, a joined segment run) without
// disturbing the panel-level memo. The scan is unchanged: it gates both the AI
// punctuation pass and heuristicPunctuate, which inserts full-width marks by
// character count and must therefore never run on a Latin/Kana run.
function textNeedsPunctuationFix(text) {
  const sample = String(text == null ? "" : text).slice(0, 3000);
  let cjk = 0;
  let punct = 0;
  // Single pass over code points. F11: the punctuation set counts BOTH the
  // full-width CJK marks and their half-width ASCII counterparts.
  for (const ch of sample) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x4e00 && cp <= 0x9fff) {
      cjk++;
    } else if (
      cp === 0xff0c || cp === 0x3002 || cp === 0xff01 || cp === 0xff1f ||
      cp === 0xff1b || cp === 0xff1a || cp === 0x3001 ||
      ch === "," || ch === "." || ch === "!" || ch === "?" ||
      ch === ";" || ch === ":"
    ) {
      punct++;
    }
  }
  return cjk >= 200 && punct / cjk < 0.02;
}

// Insert-only local断句. NEVER deletes or rewrites a character, so stripping
// punctuation from the output always yields the original character sequence.
function heuristicPunctuate(text) {
  const src = String(text || "");
  if (!src) return src;

  const CONNECTIVES = [
    "\u7136\u540e", "\u4f46\u662f", "\u6240\u4ee5", "\u56e0\u4e3a", "\u5982\u679c",
    "\u5176\u5b9e", "\u90a3\u4e48", "\u9996\u5148", "\u5176\u6b21", "\u6700\u540e",
    "\u53e6\u5916", "\u800c\u4e14", "\u4e0d\u8fc7", "\u6bd4\u5982", "\u63a5\u7740",
    "\u4e8e\u662f", "\u5e76\u4e14", "\u540c\u65f6", "\u7136\u800c", "\u5f53\u7136",
    "\u603b\u4e4b", "\u6211\u4eec", "\u4f60\u4eec", "\u4ed6\u4eec",
  ];
  const PARTICLES = [
    "\u4e86", "\u7684", "\u5427", "\u5462", "\u554a", "\u561b", "\u54e6", "\u5440",
  ];
  // F11: include half-width , . ! ? ; : so we never insert a full-width mark
  // right beside an existing half-width one (avoids "，,。" style clutter).
  const PUNCT = "\uff0c\u3002\uff01\uff1f\uff1b\uff1a\u3001,.!?;:";
  const isPunct = (ch) => PUNCT.indexOf(ch) !== -1;
  const startsConnective = (rest) =>
    CONNECTIVES.some((word) => rest.startsWith(word));

  let out = "";
  let sinceAny = 0; // chars since the last punctuation of any kind
  let sincePeriod = 0; // chars since the last sentence-ending period
  const MIN_SENTENCE = 8;

  for (let i = 0; i < src.length; i++) {
    const ch = src[i];

    if (isPunct(ch)) {
      out += ch;
      sinceAny = 0;
      // F22: full-width period/bang/question and half-width !? always end
      // a sentence. A half-width . only ends one when followed by whitespace
      // or the end of the string, so decimals (3.14) and URLs (a.com) do
      // NOT reset the 120-char guardrail (cf. background.js \.(?=\s|$) edge).
      if (
        "\u3002\uff01\uff1f!?".indexOf(ch) !== -1 ||
        (ch === "." && (i === src.length - 1 || /\s/.test(src[i + 1])))
      ) {
        sincePeriod = 0;
      }
      continue;
    }

    // Insert a comma before a connective word that starts a new clause.
    if (out && !isPunct(out[out.length - 1]) && sinceAny >= 4) {
      if (startsConnective(src.slice(i))) {
        out += "\uff0c";
        sinceAny = 0;
      }
    }

    out += ch;
    sinceAny++;
    sincePeriod++;

    // Insert a period after a sentence-final particle once the clause is long
    // enough and a new clause (or a long run) follows.
    if (
      PARTICLES.indexOf(ch) !== -1 &&
      sinceAny >= MIN_SENTENCE &&
      i < src.length - 1 &&
      !isPunct(src[i + 1])
    ) {
      if (startsConnective(src.slice(i + 1)) || sinceAny >= 20) {
        out += "\u3002";
        sinceAny = 0;
        sincePeriod = 0;
      }
    }

    // Guardrails for runs that still have no punctuation: force a period at
    // 120 chars, otherwise a comma at 60 chars.
    if (sincePeriod >= 120) {
      out += "\u3002";
      sinceAny = 0;
      sincePeriod = 0;
    } else if (sinceAny >= 60) {
      out += "\uff0c";
      sinceAny = 0;
    }
  }

  return out;
}

// Text shown for a transcript row: cached AI-restored text wins, else the free
// heuristic when the track needs it, else the raw text.
function displaySegmentText(segment, punctNeeded, ns) {
  /*
   * The cache is consulted BEFORE `needed`, so an unnamespaced key would let a
   * punctuation result cached for the platform Chinese be served for the adopted
   * original's colliding segment id.
   */
  const cached = transcriptParagraphCache.get(punctCacheKey(segment, ns));
  if (typeof cached === "string" && cached) return cached;
  const needed =
    punctNeeded === undefined ? needsPunctuationFix() : punctNeeded;
  if (needed) return heuristicPunctuate(segment.text);
  return segment.text;
}

// Updates one transcript row in place (no regroup, no scroll jump). On success
// it swaps in the restored text and clears the heuristic marker; on failure it
// keeps the heuristic text and only annotates the row's title.
function applyPunctuatedRow(segmentId, text, error) {
  const row = document.querySelector(
    `.transcript-entry[data-segment-id="${CSS.escape(segmentId)}"]`,
  );
  if (!row) return;
  if (text) {
    // F9: the restored text lives in .transcript-text (original mode) or
    // .transcript-original (zh/bilingual modes) — update whichever is present.
    const span = row.querySelector(".transcript-text, .transcript-original");
    if (span) span.innerHTML = renderSubtitleInlineMarkup(text);
    row.classList.remove("transcript-entry--punct-heuristic");
    row.removeAttribute("title");
  } else if (error) {
    row.title = `\u672c\u5730\u65ad\u53e5\uff08AI \u6807\u70b9\u4fee\u590d\u5931\u8d25\uff1a${error}\uff09`;
  }
}

// Tier-1: batch the not-yet-cached segments (<=4 segments and <=12000 chars per
// batch, matching validateTranscriptBatchRequest) and advance in waves of 2
// concurrent requests. Each success is cached and applied in place; a failed
// batch keeps its heuristic text and never blocks the rest.
async function runPunctuationFix() {
  const btn = document.getElementById("punctuateTranscriptBtn");
  if (!currentVideoId || !currentTranscript) return;

  const segments = getActiveTranscriptSegments();
  if (!Array.isArray(segments) || segments.length === 0) return;
  const punctNs = punctNamespaceForMode(currentTranscriptMode);

  const pending = segments.filter(
    (segment) => !transcriptParagraphCache.has(punctCacheKey(segment, punctNs)),
  );
  if (pending.length === 0) {
    updatePunctuateButtonVisibility();
    return;
  }

  const generation = ++punctFixGeneration;
  const total = pending.length;
  let done = 0;
  if (btn) {
    btn.disabled = true;
    btn.textContent = `\u4fee\u590d\u4e2d\u2026 0/${total}`;
  }
  setPanelBusy(true);
  try {
    const batches = [];
    let current = [];
    let currentChars = 0;
    for (const segment of pending) {
      const len = String(segment.text || "").length;
      if (
        current.length > 0 &&
        (current.length >= 4 || currentChars + len > 12000)
      ) {
        batches.push(current);
        current = [];
        currentChars = 0;
      }
      current.push(segment);
      currentChars += len;
    }
    if (current.length > 0) batches.push(current);

    const CONCURRENCY = 2;
    const runBatch = async (batch) => {
      const content = {
        segments: batch.map((segment) => ({
          id: segment.id,
          text: segment.text,
        })),
      };
      try {
        const response = await sendTranslationMessage({
          action: "punctuateTranscript",
          content,
          videoTitle: currentVideoTitle || "",
        });
        if (generation !== punctFixGeneration) return; // superseded
        if (response && response.success && Array.isArray(response.segments)) {
          response.segments.forEach((result) => {
            if (!result || typeof result.id !== "string") return;
            const source = batch.find((segment) => segment.id === result.id);
            if (!source) return;
            if (result.text) {
              transcriptParagraphCache.set(
                punctCacheKey(source, punctNs),
                result.text,
              );
              applyPunctuatedRow(source.id, result.text, null);
            } else {
              applyPunctuatedRow(
                source.id,
                null,
                result.error || "\u6807\u70b9\u4fee\u590d\u5931\u8d25",
              );
            }
          });
        } else {
          batch.forEach((segment) =>
            applyPunctuatedRow(
              segment.id,
              null,
              (response && response.error) || "\u6807\u70b9\u4fee\u590d\u5931\u8d25",
            ),
          );
        }
      } catch (error) {
        if (generation !== punctFixGeneration) return;
        batch.forEach((segment) =>
          applyPunctuatedRow(
            segment.id,
            null,
            error.message || "\u6807\u70b9\u4fee\u590d\u5931\u8d25",
          ),
        );
      } finally {
        done += batch.length;
        if (generation === punctFixGeneration && btn) {
          btn.textContent = `\u4fee\u590d\u4e2d\u2026 ${Math.min(done, total)}/${total}`;
        }
      }
    };

    let index = 0;
    while (index < batches.length) {
      if (generation !== punctFixGeneration) return;
      const wave = batches.slice(index, index + CONCURRENCY);
      index += CONCURRENCY;
      await Promise.all(wave.map(runBatch));
    }
    // F13: persist the cache ONCE after all waves (guarded by the generation
    // check) instead of after every batch, so we never hammer chrome.storage.
    if (generation === punctFixGeneration) {
      await updateCache();
    }
  } finally {
    // F1: ALWAYS clear the busy flag + heartbeat, even when this run was
    // superseded mid-flight. setPanelBusy(false) internally clears the heartbeat
    // interval, so no "in-flight replaced" path can leak panelBusy=true.
    setPanelBusy(false);
    // Button reset stays behind the generation guard: a superseded run must not
    // stomp the newer run's button state.
    if (generation === punctFixGeneration && btn) {
      const allCached = segments.every((segment) =>
        transcriptParagraphCache.has(punctCacheKey(segment, punctNs)),
      );
      btn.disabled = false;
      btn.textContent = allCached
        ? "\u5df2\u4fee\u590d \u2713"
        : "\u4fee\u590d\u6807\u70b9";
    }
  }
}

// Shows the button only when the track actually needs punctuation. Label flips
// to "\u5df2\u4fee\u590d \u2713" once every segment has a cached restoration.
function updatePunctuateButtonVisibility() {
  const btn = document.getElementById("punctuateTranscriptBtn");
  if (!btn) return;
  const punctNs = punctNamespaceForMode(currentTranscriptMode);
  if (!needsPunctuationFix(transcriptTextForMode(currentTranscriptMode))) {
    btn.style.display = "none";
    return;
  }
  btn.style.display = "";
  if (btn.disabled) return; // do not fight an in-progress fix
  const segments = getActiveTranscriptSegments();
  const allCached =
    segments.length > 0 &&
    segments.every((segment) =>
      transcriptParagraphCache.has(punctCacheKey(segment, punctNs)),
    );
  btn.textContent = allCached ? "\u5df2\u4fee\u590d \u2713" : "\u4fee\u590d\u6807\u70b9";
}

