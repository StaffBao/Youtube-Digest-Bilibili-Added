function renderTranscript(entries, mode) {
  const renderMode = mode || "original";
  const zhVerbatim = renderMode === "zh" && !!platformZhTranscript;
  const source =
    Array.isArray(entries) && entries.length
      ? entries
      : transcriptEntriesForMode(renderMode);
  if (!source || !source.length) return;
  const punctNs = punctNamespaceForMode(renderMode);

  const transcriptList = document.getElementById("transcriptList");
  transcriptList.innerHTML = "";

  // Show a small badge indicating where the transcript came from: a platform
  // subtitle track, or AI speech recognition over the video's own audio.
  const existingBadge = document.getElementById("transcriptSourceBadge");
  if (existingBadge) existingBadge.remove();

  const badge = document.createElement("div");
  badge.id = "transcriptSourceBadge";
  badge.className = "transcript-source-badge";
  /*
   * v15: the badge must describe whatever is actually on screen. In the zh
   * verbatim case that is the displaced platform track, not the adopted
   * original, so it must not inherit the original's ASR label.
   */
  const originLabel = zhVerbatim
    ? "From video subtitles"
    : currentTranscriptOrigin === "asr"
      ? "ASR 生成"
      : "From video subtitles";
  const modeLabel = zhVerbatim
    ? "简体中文 · 平台字幕原样"
    : getOriginalTranscriptLabel();
  badge.innerHTML = `<span class="source-dot source-dot--subs"></span> ${originLabel} · ${escapeHtml(modeLabel)}`;
  transcriptList.parentElement.insertBefore(badge, transcriptList);

  // Group entries using smart sentence-boundary + time-guardrail logic
  const grouped = groupTranscriptEntries(source);

  // F8: evaluate the punctuation heuristic ONCE per render, not once per row.
  const punctNeeded = needsPunctuationFix(transcriptTextForMode(renderMode));

  grouped.forEach((group) => {
    const div = document.createElement("div");
    div.className = "transcript-entry";
    div.dataset.seconds = group.start;
    div.dataset.segmentId = group.id;

    const minutes = Math.floor(group.start / 60);
    const seconds = Math.floor(group.start % 60);
    const timestamp = `${minutes}:${String(seconds).padStart(2, "0")}`;

    // v10: render the punctuation-restored text when cached, otherwise the
    // free local heuristic for punctuation-less CJK runs, otherwise the raw
    // text. The heuristic is flagged so the row can hint the one-click fix.
    const displayText = displaySegmentText(group, punctNeeded, punctNs);
    if (
      punctNeeded &&
      !transcriptParagraphCache.has(punctCacheKey(group, punctNs))
    ) {
      div.classList.add("transcript-entry--punct-heuristic");
      div.title = "本地断句，可点击修复标点";
    }

    div.innerHTML = `
      <span class="transcript-time">${timestamp}</span>
      <span class="transcript-text">${renderSubtitleInlineMarkup(displayText)}</span>
    `;

    div.addEventListener("click", (event) =>
      seekFromTranscriptEntryClick(event, group.start),
    );
    transcriptList.appendChild(div);
  });

  // Start tracking video playback for auto-scroll
  startPlaybackTracking();
  updatePunctuateButtonVisibility();
  updateOriginalLangNotice();
}

