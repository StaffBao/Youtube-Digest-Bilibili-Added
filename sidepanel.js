/**
 * True when the held transcript is a platform machine-generated Chinese track
 * (Bilibili reports these as `ai-zh`). Such a track can be the only subtitle a
 * video offers even when the audio is another language, in which case the
 * Original view is showing a machine translation rather than the original.
 */
function isHeldTrackMachineChinese() {
  return /^ai-/i.test(String(currentTranscriptLanguage || ""));
}

/** Pure detection snapshot for the currently held transcript. */
function detectHeldSourceLanguage() {
  return classifySourceLanguage({
    bodyText: currentTranscriptText || "",
    titleText: currentVideoTitle || "",
    trackLangs: currentAvailableSubtitles,
    heldTrackLang: currentTranscriptLanguage || "",
  });
}

/**
 * Swaps in an original-language transcript, keeping the displaced platform
 * Chinese so 中文 mode can still render it verbatim instead of paying to
 * translate the original back into Chinese.
 */
async function adoptOriginalTranscript(result) {
  const entries =
    result && Array.isArray(result.transcript) ? result.transcript : null;
  if (!entries || entries.length === 0) {
    throw new Error("未获得可用的原文逐字稿");
  }
  if (
    !platformZhTranscript &&
    isMostlyChineseText(String(currentTranscriptText || ""))
  ) {
    platformZhTranscript = currentTranscript;
    platformZhTranscriptText = currentTranscriptText;
    platformZhLanguage = currentTranscriptLanguage;
  }
  // Segment ids carry no origin namespace, so the held track and the new
  // original both produce `segment-0-0`. Drop the held-track caches, or a
  // Chinese-into-Chinese translation cached earlier would be served as the
  // "translation" of the new segment 0.
  const dropped = invalidateHeldSemanticCaches(currentVideoId);
  if (dropped) debugLog("Invalidated held semantic cache keys:", dropped);
  punctFixMemo = { key: null, value: false };
  await finishTranscriptLoad(result, currentVideoId);
  // v17: the held transcript just changed language basis and there is no
  // regenerate entry anymore, so a cached overview from the old track must not
  // survive. The lazy Overview trigger in switchTab rebuilds from the new track.
  if (currentAnalysis) {
    currentAnalysis = null;
    overviewTranslationCache.delete(currentVideoId);
    await saveToCache(currentVideoId);
    const overviewVisible = document
      .querySelector('.tab-panel[data-panel="overview"]')
      ?.classList.contains("active");
    if (overviewVisible) void triggerAnalysis();
  }
}

/**
 * Adopts a free non-Chinese platform track when the held track is machine
 * Chinese and the video offers one. The initial fetch sends no preferLang, so
 * Bilibili can hand back `ai-zh` even when a free original track exists — and a
 * platform track costs nothing, while ASR is billed by audio duration. This
 * therefore runs automatically, with no confirmation. Returns true on adoption.
 */
async function maybeAdoptFreeSourceTrack() {
  if (!currentVideoId || !currentTranscript) return false;
  if (platformZhTranscript) return false;
  if (!isHeldTrackMachineChinese()) return false;
  const detection = detectHeldSourceLanguage();
  if (!detection.sourceTrackLang) return false;
  try {
    const result = await chrome.runtime.sendMessage({
      action: "fetchTranscript",
      platform: currentPlatform,
      videoId: currentVideoId,
      tabId: youtubeTabId,
      preferLang: detection.sourceTrackLang,
    });
    const entries =
      result && result.success && Array.isArray(result.transcript)
        ? result.transcript
        : null;
    if (!entries || entries.length === 0) return false;
    // A platform that hands back Chinese anyway must not masquerade as the
    // original — same guard the Docs source-selection block applies.
    if (isMostlyChineseText(String((result && result.transcriptText) || ""))) {
      return false;
    }
    await adoptOriginalTranscript(result);
    return true;
  } catch (error) {
    console.error(
      "[Youtube Bilibili Digest Panel] Free source-track fetch failed:",
      error,
    );
    return false;
  }
}

