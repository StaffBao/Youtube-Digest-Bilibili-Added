/**
 * Drops the held-track semantic caches for one video, returning how many keys
 * were removed.
 *
 * groupTranscriptEntries builds ids as `segment-<index>-<startMs>` with no
 * origin namespace, so an on-demand ASR original and the platform track it
 * replaced BOTH produce `segment-0-0`. Without this, a Chinese translation
 * cached while the held track was the platform `ai-zh` subtitles would later be
 * served as the "translation" of English ASR segment 0. The same collision
 * applies to punctuation results.
 *
 * Only those two held-track namespaces are cleared. The Docs path's `:asr-src:`
 * / `:asr-en:` / `:punct:docs-src:` keys are deliberately kept: they are
 * already origin-namespaced (see punctuateDocsSegments), and reusing them is
 * what stops a panel ASR run and a Docs ASR run from billing twice.
 */
function invalidateHeldSemanticCaches(videoId) {
  if (!videoId) return 0;
  const prefixes = [`${videoId}:zh:semantic:`, `${videoId}:punct:semantic:`];
  let removed = 0;
  for (const key of Array.from(transcriptParagraphCache.keys())) {
    if (prefixes.some((prefix) => key.startsWith(prefix))) {
      transcriptParagraphCache.delete(key);
      removed += 1;
    }
  }
  return removed;
}

