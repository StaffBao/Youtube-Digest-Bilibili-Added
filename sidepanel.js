function downloadTextFile(text, filename) {
  const blob = new Blob([text], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Builds a filesystem-safe title for export filenames. Uses the same rule as
 * the Word export so .txt and .doc names agree: only the characters Windows and
 * macOS reject are replaced, CJK survives, capped at 60 characters.
 */
function safeExportTitle(title) {
  return (
    String(title || "")
      .replace(/[\\/:*?"<>|\r\n\t]/g, "_")
      .trim()
      .slice(0, 60) || "video"
  );
}

/** Formats a segment's start time as M:SS, matching the panel's own display. */
function formatSegmentClock(segment) {
  const start = Math.max(0, Math.floor(Number(segment?.start) || 0));
  const minutes = Math.floor(start / 60);
  const seconds = start % 60;
  return `${minutes}:${String(seconds).padStart(2, "0")}`;
}

