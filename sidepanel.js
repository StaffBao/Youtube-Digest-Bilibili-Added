/**
 * Returns a Map of segment -> Simplified Chinese text. Reuses whatever the
 * panel already translated and only pays for the gap, then writes the results
 * back into transcriptParagraphCache under the panel's own key, so the 中文 /
 * 双语 views and any later export share one translation pass.
 * Throws when the AI endpoint returns nothing (missing key, bad base URL).
 */
async function ensureSegmentTranslations(segments, onProgress) {
  const byId = new Map();
  segments.forEach((segment) => byId.set(String(segment.id), segment));

  const missing = segments.filter(
    (segment) =>
      !transcriptParagraphCache.has(transcriptTranslationCacheKey(segment)),
  );

  if (missing.length > 0) {
    const translated = await translateDocsSegmentsById(
      missing,
      "",
      onProgress,
    );
    if (translated.size === 0) {
      throw new Error("translation returned no segments");
    }
    translated.forEach((text, id) => {
      const segment = byId.get(String(id));
      if (segment && text) {
        transcriptParagraphCache.set(
          transcriptTranslationCacheKey(segment),
          text,
        );
      }
    });
    await saveToCache(currentVideoId).catch(() => {});
  }

  const out = new Map();
  segments.forEach((segment) => {
    out.set(
      segment,
      transcriptParagraphCache.get(transcriptTranslationCacheKey(segment)) || "",
    );
  });
  return out;
}

/**
 * Renders the plain-text body for one language mode. Grouping and punctuation
 * come from the same helpers the panel uses, so the file matches the screen.
 * Bilingual indents the translation under its source line; a segment with no
 * translation keeps an explicit marker rather than silently shifting the pair.
 */
function buildTranscriptBody(segments, mode, translations, punctNeeded, ns) {
  return segments
    .map((segment) => {
      const clock = formatSegmentClock(segment);
      const source = displaySegmentText(segment, punctNeeded, ns);
      if (mode === "zh") {
        const target = translations ? translations.get(segment) : "";
        return `[${clock}] ${target || source}`;
      }
      if (mode === "bilingual") {
        const target = translations ? translations.get(segment) : "";
        const indent = " ".repeat(clock.length + 3);
        return `[${clock}] ${source}\n${indent}${target || "[缺译]"}`;
      }
      return `[${clock}] ${source}`;
    })
    .join("\n\n");
}

async function exportTranscript() {
  const btn = document.getElementById("exportTranscriptBtn");
  const idleLabel = btn ? btn.textContent : "";
  const setBtn = (text, disabled) => {
    if (!btn) return;
    btn.textContent = text;
    btn.disabled = !!disabled;
  };
  const fail = (text) => {
    setBtn(text, false);
    setTimeout(() => setBtn(idleLabel, false), 4000);
  };

  const exportMode = TRANSCRIPT_EXPORT_MODES[currentTranscriptMode]
    ? currentTranscriptMode
    : "original";
  const segments = getActiveTranscriptSegments(exportMode);
  const hasSegments = Array.isArray(segments) && segments.length > 0;
  const punctNs = punctNamespaceForMode(exportMode);
  const punctNeeded = needsPunctuationFix(transcriptTextForMode(exportMode));

  // A Chinese-source video has no meaningful 原文 / 中文 / 双语 split — all
  // three would carry identical text — so it collapses to one unsuffixed file,
  // mirroring the Word export's zhSolo rule in generateWordDocs.
  const srcIsChinese = isMostlyChineseText(currentTranscriptText || "");
  /*
   * v15: with an adopted original, the zh export writes the displaced platform
   * Chinese verbatim — no translation, no token cost — and must neither collapse
   * into "source" nor claim to be translated from the original.
   */
  const zhVerbatim = exportMode === "zh" && !!platformZhTranscript;
  const mode = zhVerbatim ? "zhVerbatim" : srcIsChinese ? "source" : exportMode;
  const meta = TRANSCRIPT_EXPORT_MODES[mode];

  let translations = null;
  if (mode === "zh" || mode === "bilingual") {
    if (!hasSegments) {
      fail("无逐句字幕可翻译");
      return;
    }
    setBtn("翻译中…", true);
    // background broadcasts docsProgress once per batch, but the panel's global
    // listener deliberately ignores phase "notes" so a background broadcast can
    // never overwrite the Word export's own progress line. Subscribe locally for
    // the lifetime of this export instead of widening that whitelist.
    const onBatchProgress = (message) => {
      if (
        message &&
        message.action === "docsProgress" &&
        message.phase === "notes" &&
        message.chunk &&
        message.total
      ) {
        setBtn(`翻译中… (${message.chunk}/${message.total})`, true);
      }
    };
    chrome.runtime.onMessage.addListener(onBatchProgress);
    try {
      translations = await ensureSegmentTranslations(segments, (message) =>
        setBtn(message, true),
      );
    } catch (error) {
      const cancelled = /DOCS_CANCELLED/.test(String((error && error.message) || error));
      console.error(
        "[Youtube Bilibili Digest Panel] Transcript export translation failed:",
        error,
      );
      fail(cancelled ? "已取消" : "翻译失败，请检查 AI 接口");
      return;
    } finally {
      chrome.runtime.onMessage.removeListener(onBatchProgress);
    }
  }

  const body = hasSegments
    ? buildTranscriptBody(segments, mode, translations, punctNeeded, punctNs)
    : transcriptTextForMode(exportMode);

  const videoUrl =
    currentPlatform === "bilibili"
      ? `https://www.bilibili.com/video/${currentVideoId}`
      : `https://youtube.com/watch?v=${currentVideoId}`;

  const rule = "—".repeat(60);
  let exportText = "";
  exportText += `${meta.banner}\n`;
  exportText += `${"=".repeat(60)}\n\n`;
  exportText += `Title: ${currentVideoTitle || "Unknown"}\n`;
  exportText += `Channel: ${currentChannelName || "Unknown"}\n`;
  exportText += `URL: ${videoUrl}\n`;
  exportText += `Mode: ${meta.modeName}\n`;
  if (currentTranscriptOrigin === "asr") {
    exportText += `Subtitle source: ASR 生成\n`;
  }
  exportText += `\n${rule}\n\n`;

  if (currentVideoDescription) {
    exportText += `DESCRIPTION:\n${currentVideoDescription}\n`;
    exportText += `\n${rule}\n\n`;
  }

  exportText += `TRANSCRIPT:\n\n${body}\n`;
  exportText += `\n${rule}\n`;
  exportText += `Exported by Youtube Bilibili Digest\n`;

  const filename = `Transcript_${safeExportTitle(currentVideoTitle)}${meta.suffix}.txt`;
  downloadTextFile(exportText, filename);
  setBtn("✓ 已导出", false);
  setTimeout(() => setBtn(idleLabel, false), 2000);
}

