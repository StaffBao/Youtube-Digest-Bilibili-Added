// ASR FALLBACK — AI-generated subtitles when the video has none
// ============================================================

// Chunk length keeps each base64 payload under the provider's input limit
// (180s of 16-bit 16kHz mono PCM ≈ 5.8MB raw ≈ 7.7MB base64).
const ASR_CHUNK_SECONDS = 180;
// Bilibili: smaller chunks give more exact time anchors, so the proportional
// timestamp estimate drifts far less (a silent intro stays inside its own chunk).
const ASR_CHUNK_SECONDS_BILIBILI = 60;
// Bilibili audio is decoded one segment at a time, so the practical limit is
// ASR cost/time rather than memory.
const ASR_MAX_DURATION_SECONDS = 4 * 60 * 60;
const ASR_TARGET_SAMPLE_RATE = 16000;
const ASR_REQUEST_TIMEOUT_MS = 240_000;
// Chunks are independent, so transcribe several concurrently. Keep this low:
// providers may rate-limit, and each in-flight chunk holds ~35MB of PCM/WAV.
const ASR_PARALLEL_WORKERS = 4;

async function getAsrSettings() {
  const stored = await chrome.storage.local.get(YTD_SETTINGS.STORAGE_KEY);
  const settings = YTD_SETTINGS.normalize(stored[YTD_SETTINGS.STORAGE_KEY]);
  return {
    enabled: settings.asrEnabled,
    // An empty dedicated ASR key falls back to the main AI key.
    apiKey: settings.asrApiKey || settings.aiApiKey,
    baseUrl: settings.asrBaseUrl,
    model: settings.asrModel,
    // v11: expose the request protocol (chat-audio vs whisper-multipart) and the
    // optional source-language hint. normalize() already sanitized both; calling
    // the sanitizers again is idempotent and keeps this the single trusted shape.
    protocol: YTD_SETTINGS.sanitizeAsrProtocol(settings.asrProtocol),
    language: YTD_SETTINGS.sanitizeAsrLanguage(settings.asrLanguage),
  };
}

