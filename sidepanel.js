async function startDigest(videoId, videoUrl) {
  // Check if we already have this video loaded in memory
  if (videoId === currentVideoId && currentAnalysis) {
    showState("results");
    return;
  }

  // Every video change invalidates observer work and in-flight translations.
  if (videoId !== currentVideoId) {
    translationGeneration += 1;
    punctFixGeneration += 1;
    punctFixMemo = { key: null, value: false }; // F8: new video, stale memo
    // F19: a new video must re-seed the Docs language checkbox defaults
    // instead of inheriting the previous video's user toggles. Clearing
    // autoInit lets renderDocsLanguageOptions re-apply its defaults.
    [
      "docsOptSource",
      "docsOptZh",
      "docsOptBilingual",
      // v11 (W8): the content switches are re-seeded per video for the same
      // reason - a new video must not inherit the previous one's toggles.
      "docsOptMeta",
      "docsOptOverview",
      "docsOptNotes",
      "docsOptTimestamps",
    ].forEach((id) => {
      delete document.getElementById(id)?.dataset.autoInit;
    });
    // v11 (W8): the on-demand source-track memo and the captured ASR entries
    // belong to the previous video; drop them so they can never be reused.
    docsSourceTrackMemo = null;
    docsAsrSourceEntries = null;
    docsAsrSourceEstimated = false;
    docsAsrSourceVideoId = null;
    // The transcript source badge must not carry the previous video's origin;
    // the cache-restore branch and finishTranscriptLoad set the real value.
    currentTranscriptOrigin = "platform";
    if (transcriptScrollObserver) transcriptScrollObserver.disconnect();
    transcriptScrollObserver = null;
  }

  // Check cache for this video
  const cached = await loadFromCache(videoId);
  if (cached) {
    debugLog("Loading from cache:", videoId);
    currentVideoId = videoId;
    currentVideoUrl = videoUrl;
    currentAnalysis = cached.analysis || null;
    currentTranscript = cached.transcript;
    currentTranscriptText = cached.transcriptText;
    currentTranscriptTimestamped = cached.transcriptTimestamped;
    currentTranscriptLanguage = cached.transcriptLanguage || null;
    currentAvailableSubtitles = cached.availableSubtitles || null;
    // Older caches predate the field: an absent origin is a platform transcript.
    currentTranscriptOrigin = cached.transcriptOrigin === "asr" ? "asr" : "platform";
    // v15: the platform Chinese track displaced by an on-demand original. Absent
    // in older caches, and absent whenever no original was ever fetched.
    platformZhTranscript = cached.platformZhTranscript || null;
    platformZhTranscriptText = cached.platformZhTranscriptText || null;
    platformZhLanguage = cached.platformZhLanguage || null;
    isAnalysisLoading = false;

    // Restore semantic-segment translations from persistent storage.
    if (cached.paragraphCache) {
      for (const [key, value] of Object.entries(cached.paragraphCache)) {
        transcriptParagraphCache.set(key, value);
      }
    }

    if (currentVideoTitle || currentChannelName) {
      const videoInfo = document.getElementById("videoInfo");
      document.getElementById("videoTitle").textContent = currentVideoTitle;
      document.getElementById("videoChannel").textContent = currentChannelName;
      videoInfo.style.display = "block";
    }

    // Always render transcript first
    renderTranscript();
    renderDocsLanguageOptions();
    syncDocsContentOptions();
    // v15: a cache written before this feature existed can still hold an `ai-zh`
    // track. Retrying the free original is harmless — it costs nothing, and once
    // adopted it is persisted via platformZhTranscript so this short-circuits.
    await maybeAdoptFreeSourceTrack();

    // Render analysis if we have it cached
    if (currentAnalysis) {
      renderAnalysisWithMode();
      highlightMomentsOnPage(currentAnalysis.keyMoments);
    }

    showState("results");
    document.getElementById("tabsNav").style.display = "flex";

    // Load notes for this video
    loadNotes(videoId);

    // Setup explain feature
    setupExplainFeature();
    if (currentTranscriptMode !== "original") translateTranscript();
    return;
  }

  currentVideoId = videoId;
  currentVideoUrl = videoUrl;
  currentAnalysis = null;
  currentTranscript = null;
  currentTranscriptText = null;
  currentTranscriptTimestamped = null;
  currentTranscriptLanguage = null;
  currentAvailableSubtitles = null;
  platformZhTranscript = null;
  platformZhTranscriptText = null;
  platformZhLanguage = null;
  originalLangNoticeDismissed = false;
  isAnalysisLoading = false;
  // Reset overview language mode to original when switching videos
  currentOverviewMode = "original";
  overviewTranslationGeneration += 1;
  setOverviewModeButtons("original");

  if (currentVideoTitle || currentChannelName) {
    const videoInfo = document.getElementById("videoInfo");
    document.getElementById("videoTitle").textContent = currentVideoTitle;
    document.getElementById("videoChannel").textContent = currentChannelName;
    videoInfo.style.display = "block";
  }

  showState("loading");
  updateLoading("Fetching transcript", "");

  const transcriptResult = await chrome.runtime.sendMessage({
    action: "fetchTranscript",
    platform: currentPlatform,
    videoId: videoId,
    tabId: youtubeTabId,
  });

  if (!transcriptResult.success) {
    // No platform subtitles: offer AI speech recognition if the user opted
    // in and configured an ASR endpoint (see Youtube Bilibili Digest Settings).
    const config = await chrome.runtime
      .sendMessage({ action: "checkConfig" })
      .catch(() => null);

    const isNoSubtitles = transcriptResult.error === "NO_SUBTITLES";
    const isLoginRequired = transcriptResult.error === "BILI_LOGIN_REQUIRED";
    const canUseAsr = config?.asrEnabled && config?.asrConfigured;

    /*
     * v15: a relay/connection failure is not a missing-subtitles situation.
     * Offering ASR here sends the user down a path that depends on the same
     * unreachable page state and fails again, so report it honestly instead.
     */
    const failureText = String(
      (transcriptResult &&
        (transcriptResult.message || transcriptResult.error)) ||
        "",
    );
    const isConnectionFailure =
      /Receiving end does not exist|Could not establish connection|No video tab found/i.test(
        failureText,
      );
    if (isConnectionFailure) {
      showError(
        "Cannot reach the video page",
        "The extension could not talk to this tab. Refresh the video tab and try again.",
      );
      return;
    }

    // A late-opened Bilibili page can fail a subtitle query without lacking
    // subtitles. Preserve a free retry instead of replacing it with paid ASR.
    if (currentPlatform === "bilibili" && !isNoSubtitles) {
      showError(
        isLoginRequired ? "Login required" : "Could not read Bilibili subtitles",
        transcriptResult.message || transcriptResult.error,
      );
      return;
    }

    if (canUseAsr) {
      showState("error");
      if (isNoSubtitles) {
        document.getElementById("errorTitle").textContent =
          "No subtitles available";
        document.getElementById("errorMessage").textContent =
          "This video has no subtitles. You can let AI transcribe the audio to generate subtitles (ASR).";
      } else if (isLoginRequired) {
        document.getElementById("errorTitle").textContent = "Login required";
        document.getElementById("errorMessage").textContent =
          `${transcriptResult.message || "Bilibili subtitles require a logged-in account."} You can also try AI transcription (ASR).`;
      } else {
        document.getElementById("errorTitle").textContent =
          "No transcript found";
        document.getElementById("errorMessage").textContent =
          `${transcriptResult.message || transcriptResult.error || "This video has no subtitles."} ` +
          "You can let AI transcribe the audio to generate subtitles (ASR).";
      }
      document.getElementById("errorBtn").textContent = "Generate AI Subtitles";
      errorAction = () => void runAsrTranscription();
    } else {
      showError(
        isNoSubtitles
          ? "No subtitles available"
          : "No transcript found",
        transcriptResult.message || transcriptResult.error,
      );
    }
    return;
  }

  await finishTranscriptLoad(transcriptResult, videoId);
  // v15: Bilibili can hand back its machine-Chinese `ai-zh` track even when the
  // video also offers a free original-language track, because this fetch sends
  // no preferLang. Adopting a platform track costs nothing, so do it here
  // without asking; the paid ASR path stays behind the notice bar's button.
  await maybeAdoptFreeSourceTrack();
  // DON'T run LLM analysis automatically - wait for user to click Overview tab
  // This saves tokens when user just wants to see the transcript
}

/**
 * Shared tail of a successful transcript load — used both by the direct
 * platform fetch and by the ASR fallback, so the rest of the panel (render,
 * notes, explain, cache) behaves identically either way.
 */
async function finishTranscriptLoad(transcriptResult, videoId) {
  currentTranscript = transcriptResult.transcript;
  currentTranscriptText = transcriptResult.transcriptText;
  currentTranscriptTimestamped = transcriptResult.transcriptTextTimestamped;
  currentTranscriptLanguage = transcriptResult.language || null;
  currentAvailableSubtitles = transcriptResult.availableSubtitles || null;
  currentTranscriptOrigin = transcriptResult?.origin === "asr" ? "asr" : "platform";

  // Render transcript immediately (no LLM needed)
  renderTranscript();
  renderDocsLanguageOptions();
  syncDocsContentOptions();
  showState("results");
  document.getElementById("tabsNav").style.display = "flex";

  // Load notes for this video
  loadNotes(videoId);

  // Setup explain feature for text selection
  setupExplainFeature();
  if (currentTranscriptMode !== "original") translateTranscript();

  // Save transcript to cache (without analysis)
  await saveToCache(videoId);
}

