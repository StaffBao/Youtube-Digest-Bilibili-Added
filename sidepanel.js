// Port of background.js isMostlyChinese's character counters.
function countScriptChars(text) {
  const sample = String(text || "").slice(0, 5000);
  return {
    cjk: (sample.match(/[\u4e00-\u9fff]/g) || []).length,
    kana: (sample.match(/[\u3040-\u30ff]/g) || []).length,
    hangul: (sample.match(/[\uac00-\ud7af]/g) || []).length,
    latin: (sample.match(/[a-zA-Z]/g) || []).length,
  };
}

// v11: single source of truth for "is this text mostly Chinese". The counter
// regexes and the return expression are byte-identical to background.js
// isMostlyChinese (line 2348) so the panel and the service worker can never
// disagree about whether a transcript is the Chinese source or a foreign one.
function isMostlyChineseText(text) {
  const sample = String(text || "").slice(0, 5000);
  const cjk = (sample.match(/[\u4e00-\u9fff]/g) || []).length;
  const kana = (sample.match(/[\u3040-\u30ff]/g) || []).length;
  const hangul = (sample.match(/[\uac00-\ud7af]/g) || []).length;
  const latin = (sample.match(/[a-zA-Z]/g) || []).length;
  return cjk >= kana + hangul + latin;
}

// v11: pure classification of what language the video is really in versus what
// subtitle track the panel holds. Reads NO DOM and NO globals (unit-testable);
// detectDocSourceLanguage feeds it the live state and layers the manual override
// on top. "en" is the legacy field name but its meaning is generalized to
// "non-Chinese source" (Japanese / Korean / French / ... behave the same).
function classifySourceLanguage({
  bodyText,
  titleText,
  trackLangs,
  heldTrackLang,
} = {}) {
  const body = countScriptChars(bodyText || "");
  const title = countScriptChars(titleText || "");
  const foreign = body.kana + body.hangul;

  // heldLang bucketing is unchanged from v10 (kept for existing consumers).
  let heldLang;
  if (foreign > body.cjk && foreign > body.latin && foreign > 0) {
    heldLang = "other"; // Japanese / Korean dominant
  } else if (body.cjk >= body.latin && body.cjk > 0) {
    heldLang = "zh";
  } else if (body.latin >= body.cjk * 2 && body.latin > 0) {
    heldLang = "en";
  } else if (title.cjk >= title.latin && title.cjk > 0) {
    heldLang = "zh";
  } else if (title.latin > title.cjk) {
    heldLang = "en";
  } else {
    heldLang = "other";
  }

  // v11: heldIsChinese uses the shared isMostlyChineseText formula; when the
  // body is empty (no transcript text yet) it falls back to the title.
  const heldIsChinese = isMostlyChineseText(
    bodyText && String(bodyText).trim() ? bodyText : titleText || "",
  );

  const isAiZhHeld = /^ai-/i.test(String(heldTrackLang || ""));
  // F7: distinguish "we know the track list and there is no source track" from
  // "the track list is unknown" (old caches / YouTube). Only the former may
  // assert that the non-Chinese original is unavailable.
  const tracksKnown = Array.isArray(trackLangs);

  // v11: first NON-Chinese track (was: first "en" track). This is the core fix -
  // a Japanese/Korean original track must count as an available source track.
  const langs = tracksKnown
    ? trackLangs.map((track) => String((track && track.lang) || ""))
    : [];
  const sourceTrackLang =
    langs.find((lang) => lang && !/^(zh|ai-zh)/i.test(lang)) || "";
  const sourceTrackAvailable = !!sourceTrackLang;
  // Alias kept for existing consumers (3977/4104/4182): true only when the first
  // non-Chinese track happens to be an English one.
  const enTrackAvailable = /^en/i.test(sourceTrackLang);

  // R4-m4: "the title is written in a non-Chinese script" - the exact negation
  // of the shared isMostlyChineseText formula (cjk >= kana + hangul + latin), so
  // kana/hangul count the same way latin always did. Comparing latin alone read
  // a pure-Japanese / pure-Korean title as Chinese and hid the source track.
  const titleNonChineseDominant =
    title.cjk < title.latin + title.kana + title.hangul;

  // v11: videoLang - "en" now means "non-Chinese source". A non-Chinese held body
  // is always a foreign source (covers ja/ko exactly as v10's heldLang "other"
  // branch did); a Chinese held body only counts as foreign when it is an ai-zh
  // track AND a real non-Chinese track or a non-Chinese-script title exists.
  let videoLang;
  if (!heldIsChinese) {
    videoLang = "en";
  } else {
    videoLang =
      isAiZhHeld && (sourceTrackAvailable || titleNonChineseDominant)
        ? "en"
        : "zh";
  }

  // v11: sourceViaAsr - a Chinese-held, foreign-source video with a known track
  // list but no non-Chinese track: the original can only come from ASR over the
  // video's own audio. englishViaAsr is kept as an alias (consumers 3299/4118/4158).
  const sourceViaAsr =
    heldIsChinese && videoLang !== "zh" && tracksKnown && !sourceTrackAvailable;

  const evidence =
    `持有字幕：${heldTrackLang || heldLang}` +
    `（正文 CJK ${body.cjk} / 拉丁 ${body.latin} / 假名 ${body.kana} / 谚文 ${body.hangul}）` +
    (isAiZhHeld ? "，B 站 AI 中文字幕" : "") +
    (sourceTrackAvailable
      ? `，存在非中文字幕轨（${sourceTrackLang}）`
      : "，无非中文字幕轨");

  return {
    heldLang,
    heldIsChinese,
    videoLang,
    isAiZhHeld,
    tracksKnown,
    sourceTrackAvailable,
    sourceTrackLang,
    enTrackAvailable,
    sourceViaAsr,
    englishViaAsr: sourceViaAsr,
    evidence,
  };
}

// v11: language-code -> Chinese display name for the Docs source labels. Purely
// cosmetic; unknown codes fall back to the generic "原文" wording.
const DOCS_SOURCE_LANG_NAMES = {
  en: "英文",
  ja: "日文",
  ko: "韩文",
  fr: "法文",
  de: "德文",
  es: "西班牙文",
  ru: "俄文",
  pt: "葡萄牙文",
  it: "意大利文",
};
function docsSourceLangName(hint) {
  const code = String(hint || "")
    .toLowerCase()
    .split("-")[0];
  return DOCS_SOURCE_LANG_NAMES[code] || "";
}

// Decides what language the video is really in versus what subtitle track the
// panel currently holds, then layers the session-only manual override on top of
// the pure classification. Bilibili often hands back an `ai-zh` track for a
// non-Chinese video; when that happens and a non-Chinese track exists (or the
// title is mostly non-Chinese) the video is treated as a foreign source so the
// tab can offer the original / bilingual products.
function detectDocSourceLanguage() {
  const classification = classifySourceLanguage({
    bodyText: currentTranscriptText || "",
    titleText: currentVideoTitle || "",
    trackLangs: currentAvailableSubtitles,
    heldTrackLang: currentTranscriptLanguage || "",
  });

  // Session-only manual override (never persisted) - v10 lines 3994-3997.
  let videoLang = classification.videoLang;
  const overrideEl = document.getElementById("docsLangOverride");
  const override = overrideEl ? overrideEl.value : "auto";
  if (override === "en") videoLang = "en";
  else if (override === "zh") videoLang = "zh";

  // v11: #docsSrcLang is added to the HTML by a later task; read it defensively
  // and treat a missing element (or empty value) as "auto".
  const srcLangEl = document.getElementById("docsSrcLang");
  const srcLang = srcLangEl && srcLangEl.value ? srcLangEl.value : "auto";
  // Concrete source-language hint: explicit dropdown first, then the real
  // non-Chinese track language, else "" (let the ASR service auto-detect).
  const sourceLangHint =
    srcLang && srcLang !== "auto"
      ? srcLang
      : classification.sourceTrackLang || "";

  // sourceViaAsr/englishViaAsr must reflect the OVERRIDDEN videoLang, exactly as
  // the v10 code computed them after applying the override.
  const sourceViaAsr =
    classification.heldIsChinese &&
    videoLang !== "zh" &&
    classification.tracksKnown &&
    !classification.sourceTrackAvailable;

  return Object.assign({}, classification, {
    videoLang,
    sourceViaAsr,
    englishViaAsr: sourceViaAsr,
    sourceLangHint,
  });
}

// Renders the pre-generation checkbox matrix and hint. Called after a transcript
// load, from cache, when the Docs tab opens, and when the manual override
// changes. Keeps the fieldset hidden when no subtitles are loaded.
// v10: sequence token guarding the async ASR-availability refinement inside
// renderDocsLanguageOptions, so a stale storage read can never upgrade the
// options belonging to an already-superseded render.
let docsOptsRenderSeq = 0;
// F25: cache the ASR-availability probe so case A can paint its FINAL
// enabled/disabled state synchronously, removing the disabled+unchecked middle
// window during which a generate click would silently yield Chinese-only. The
// cache is dropped whenever the settings key changes in chrome.storage.
let docsAsrUsableCache; // undefined = not probed yet; else boolean
let docsAsrUsablePromise = null;
function probeDocsAsrUsable() {
  if (docsAsrUsableCache !== undefined) {
    return Promise.resolve(docsAsrUsableCache);
  }
  if (!docsAsrUsablePromise) {
    docsAsrUsablePromise = getAsrSettings()
      .then((s) => {
        docsAsrUsableCache = !!(s && s.enabled && s.apiKey);
        return docsAsrUsableCache;
      })
      .catch(() => {
        docsAsrUsablePromise = null;
        docsAsrUsableCache = false;
        return false;
      });
  }
  return docsAsrUsablePromise;
}
chrome.storage.onChanged.addListener((changes, area) => {
  if (area === "local" && changes[YTD_SETTINGS.STORAGE_KEY]) {
    docsAsrUsableCache = undefined;
    docsAsrUsablePromise = null;
  }
});

function renderDocsLanguageOptions() {
  // F28: bump the render token for EVERY render (before the early returns) so
  // any in-flight async ASR upgrade from a superseded render is always stale.
  const seq = ++docsOptsRenderSeq;
  const fieldset = document.getElementById("docsLangOptions");
  if (!fieldset) return;
  const sourceOpt = document.getElementById("docsOptSource");
  const zhOpt = document.getElementById("docsOptZh");
  const bilingualOpt = document.getElementById("docsOptBilingual");
  // Target the inner text span, never the whole hint container, so the manual
  // override <select> inside #docsLangHint is preserved across re-renders.
  const hint = document.getElementById("docsLangHintText");

  const setEnabled = (el, enabled, defaultChecked) => {
    if (!el) return;
    el.disabled = !enabled;
    if (!enabled) {
      el.checked = false;
      // Clear autoInit so the default is re-applied when it is enabled again.
      delete el.dataset.autoInit;
    } else if (el.dataset.autoInit !== "1") {
      // F10: seed the checked state only once; never override a box the user has
      // already been able to interact with.
      el.checked = !!defaultChecked;
      el.dataset.autoInit = "1";
    }
  };
  // Replace a wrapping <label>'s trailing text node without touching its input.
  const setLabelText = (el, text) => {
    const label = el && el.parentElement;
    if (!label) return;
    for (let i = label.childNodes.length - 1; i >= 0; i--) {
      if (label.childNodes[i].nodeType === Node.TEXT_NODE) {
        label.childNodes[i].nodeValue = " " + text;
        return;
      }
    }
    label.appendChild(document.createTextNode(" " + text));
  };

  if (!currentTranscriptText || !currentTranscriptText.trim()) {
    fieldset.style.display = "none";
    return;
  }

  const detection = detectDocSourceLanguage();
  const { heldLang, videoLang, enTrackAvailable, tracksKnown } = detection;
  fieldset.style.display = "";

  // v11: label the source product with the concrete language name when known
  // (e.g. "日文原文逐字稿"), else a language-agnostic wording.
  const srcLangName = docsSourceLangName(detection.sourceLangHint);
  setLabelText(
    sourceOpt,
    srcLangName
      ? `${srcLangName}原文逐字稿`
      : "原文逐字稿（视频原始语言）",
  );

  let hintText = detection.evidence;
  if (videoLang === "zh") {
    setEnabled(sourceOpt, false, false);
    setEnabled(bilingualOpt, false, false);
    setEnabled(zhOpt, true, true);
    hintText += "\u3002\u89c6\u9891\u8bed\u8a00\u4e3a\u4e2d\u6587\uff0c\u4ec5\u751f\u6210\u4e2d\u6587\u9010\u5b57\u7a3f\u3002";
  } else if (detection.englishViaAsr) {
    // F23: single source of truth - this branch is entered exactly when
    // detectDocSourceLanguage().englishViaAsr is true, the SAME flag
    // generateWordDocs consults, so the UI can never promise ASR that generation
    // will not perform. F24: disable source/bilingual WITHOUT clearing
    // `checked`/`dataset.autoInit` (never setEnabled(...,false,false) here) so a
    // user choice survives switchTab / override re-renders; the upgrade below
    // seeds defaults only for boxes the user has not interacted with.
    if (sourceOpt) sourceOpt.disabled = true;
    if (bilingualOpt) bilingualOpt.disabled = true;
    setEnabled(zhOpt, true, true);
    hintText +=
      currentPlatform === "bilibili"
        ? "。B 站仅下发中文 AI 字幕，无非中文字幕轨。"
        : "。当前仅持有中文字幕轨，无非中文字幕轨。";
    // F25: paint the FINAL state synchronously whenever the ASR probe is already
    // cached, so there is no disabled+unchecked window in which a generate click
    // silently yields Chinese-only. Only the first (cold) probe upgrades in place
    // once the storage read lands; during that cold window the options stay in
    // the conservative Chinese-only state that promises no English.
    const applyAsrState = (usable, immediate) => {
      // v11: generalize the copy from "英文" to the concrete source language.
      const label = srcLangName ? `${srcLangName}原文` : "原文（视频原始语言）";
      const suffix = usable
        ? `${label}将在生成时经 ASR 从原音频转写（分钟级耗时、按音频时长计费），中文 / ${srcLangName || "原文"}·中文对照据此原文生成。`
        : `在设置中启用 AI 字幕(ASR) 并配置音频模型（qwen3-asr-flash）后，可从原音频生成${srcLangName || ""}原文逐字稿。`;
      if (usable) {
        setLabelText(sourceOpt, `${label}逐字稿（经 ASR 从原音频生成）`);
        setEnabled(sourceOpt, true, true);
        setEnabled(zhOpt, true, true);
        setEnabled(bilingualOpt, true, false);
      }
      if (immediate) hintText += suffix;
      else if (hint) hint.textContent = hintText + suffix;
    };
    probeDocsAsrUsable();
    if (docsAsrUsableCache !== undefined) {
      applyAsrState(docsAsrUsableCache, true);
    } else {
      probeDocsAsrUsable().then((usable) => {
        if (seq !== docsOptsRenderSeq) return; // F28: superseded render
        if (fieldset.style.display === "none") return; // F28: fieldset hidden
        if (!detectDocSourceLanguage().englishViaAsr) return; // double insurance
        applyAsrState(usable, false);
      });
    }
  } else {
    // English video, OR held=zh/video=en with an UNKNOWN track list (old cache /
    // YouTube). Enable all three; generateWordDocs soft-degrades (F2) if the
    // English track turns out to be missing at generation time.
    setEnabled(sourceOpt, true, true);
    setEnabled(zhOpt, true, true);
    setEnabled(bilingualOpt, true, false);
    hintText +=
      heldLang === "zh" && videoLang === "en" && !tracksKnown
        ? "。字幕轨列表未知，将在生成时按需探测原文轨。"
        : `\u3002\u9ed8\u8ba4\u751f\u6210\u539f\u6587 + \u4e2d\u6587\u4e24\u4efd\u9010\u5b57\u7a3f\uff0c\u53ef\u52a0\u9009${
            srcLangName || "\u539f\u6587"
          }\u00b7\u4e2d\u6587\u5bf9\u7167\u3002`;
  }

  // v10: ai-zh-only video whose language is NOT confirmed English (for example
  // a Chinese title makes videoLang "zh"). Never auto-run ASR on a possibly
  // Chinese video; guide the user to the manual override instead.
  if (
    videoLang === "zh" &&
    detection.isAiZhHeld &&
    tracksKnown &&
    !enTrackAvailable
  ) {
    hintText +=
      "若原音频为非中文，请在上方『视频语言』下拉选择『原文（非中文）』，以启用经 ASR 生成原文逐字稿。";
  }

  if (hint) hint.textContent = hintText;
}

